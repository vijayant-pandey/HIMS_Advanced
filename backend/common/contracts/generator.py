"""Generate the per-endpoint contracts and the requirements traceability matrix (HIMS-DOC-001).

Output (generated, never edited by hand):

* ``docs/architecture/api-and-integrations/endpoints/``: one file per area with every endpoint
  in the spec 29.5 template, plus an index;
* ``docs/requirements/traceability.md``: every Phase 1 requirement with its record, endpoints,
  tests and pull requests (spec 25.3).

Sources: the code (``inventory``, ``reach``), the published contract ``docs/api/openapi.yaml``,
the backend tests, the backlog, the tracker's PR history and the requirement records.
Regenerate with ``python manage.py api_contracts``; ``--check`` fails when the committed files
are out of date (a test runs the same check in CI).
"""

