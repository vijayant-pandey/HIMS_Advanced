@cache
def setting_default(name: str) -> str:
    """The default written in base.py, so the documents are the same on every PC and in CI
    (test settings and .env files change the live values)."""
    text = BASE_SETTINGS.read_text(encoding="utf-8")
    match = re.search(rf'env\.\w+\(\s*"{name}"[^)]*?default=([^,)]+)', text)
    if not match:
        raise ValueError(f"No default for {name} in {BASE_SETTINGS.name}")
    value = match.group(1).strip().strip('"')
    return value[:-2] if value.endswith(".0") else value


def throttle_text(scope: str) -> str:
    who = {"anon": "not signed in", "user": "signed in"}.get(scope, scope.replace("_", " "))
    rate = setting_default(f"HIMS_THROTTLE_{scope.upper()}")
    return f"{who}: {rate} per address (`HIMS_THROTTLE_{scope.upper()}`)"


@lru_cache(maxsize=1)
def openapi() -> dict:
    return yaml.safe_load(OPENAPI.read_text(encoding="utf-8"))


def _shape(path: str) -> str:
    """``/beds/{pk}/`` and ``/beds/{id}/`` are the same path (OpenAPI names ``pk`` ``id``)."""
    return re.sub(r"\{[^}]+\}", "{}", path)


@lru_cache(maxsize=1)
def _operations() -> dict[tuple[str, str], dict]:
    found = {}
    for path, methods in openapi()["paths"].items():
        for method, spec in methods.items():
            found[(_shape(path), method)] = spec
    return found


def operation(endpoint) -> dict:
    return _operations().get((_shape(endpoint.path), endpoint.method.lower()), {})


def _schema_name(content: dict | None) -> str:
    for media in (content or {}).values():
        schema = media.get("schema", {})
        ref = schema.get("$ref") or schema.get("items", {}).get("$ref", "")
        if ref:
            name = ref.rsplit("/", 1)[-1]
            return f"list of `{name}`" if "items" in schema else f"`{name}`"
        if schema.get("type") == "string" and schema.get("format") == "binary":
            return "file"
        if schema:
            return f"`{schema.get('type', 'object')}`"
    return ""


def _fields(content: dict | None) -> str:
    schemas = openapi().get("components", {}).get("schemas", {})
    for media in (content or {}).values():
        ref = media.get("schema", {}).get("$ref", "")
        schema = schemas.get(ref.rsplit("/", 1)[-1], {}) if ref else {}
        required = set(schema.get("required", []))
        found = []
        for name, spec in schema.get("properties", {}).items():
            if spec.get("readOnly"):
                continue
            limits = []
            if name in required:
                limits.append("required")
            if "maxLength" in spec:
                limits.append(f"≤ {spec['maxLength']} characters")
            if any(key in spec for key in ("enum", "allOf", "oneOf", "$ref")):
                limits.append("one of the listed values")
            if "format" in spec and spec["format"] in {"date", "date-time", "uuid", "email"}:
                limits.append(spec["format"])
            found.append(f"`{name}`" + (f" ({', '.join(limits)})" if limits else ""))
        return ", ".join(found)
    return ""


def _error_statuses() -> dict[str, int]:
    found = {}
    pending = [DomainError]
    while pending:
        cls = pending.pop()
        found.setdefault(cls.code, cls.status_code)
        pending.extend(cls.__subclasses__())
    found.update(
        VALIDATION_ERROR=400,
        NOT_AUTHENTICATED=401,
        PERMISSION_DENIED=403,
        NOT_FOUND=404,
        RATE_LIMITED=429,
        MALFORMED_REQUEST=400,
        UNSUPPORTED_MEDIA_TYPE=415,
    )
    return found


@lru_cache(maxsize=1)
def roles_by_permission() -> dict[str, list[str]]:
    found = defaultdict(list)
    for role in SYSTEM_ROLES.values():
        for code in role["permissions"]:
            found[code].append(role["name"])
    return found


@lru_cache(maxsize=1)
def backlog() -> dict[str, tuple[str, str]]:
    """Phase 1 tickets: ID -> (title, status)."""
    found = {}
    for line in BACKLOG.read_text(encoding="utf-8").splitlines():
        cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
        if len(cells) >= 3 and _TICKET.fullmatch(cells[0]):
            found[cells[0]] = (cells[1], cells[2])
    return found


def is_done(status: str) -> bool:
    return status.startswith("Done")


def _expand(text: str, known) -> set[str]:
    found = set(_TICKET.findall(text))
    for prefix, first, last in re.findall(r"(HIMS-[A-Z]+-)(\d{3})\.\.(\d{3})", text):
        found.update(f"{prefix}{n:03d}" for n in range(int(first), int(last) + 1))
    for prefix, rest in re.findall(r"(HIMS-[A-Z]+-)(\d{3}(?:/\d{3})+)", text):
        found.update(prefix + n for n in rest.split("/"))
    for prefix in re.findall(r"(HIMS-[A-Z]+-)\*", text):
        found.update(ticket for ticket in known if ticket.startswith(prefix))
    return found & set(known)


@lru_cache(maxsize=1)
def pull_requests() -> dict[str, list[str]]:
    """Ticket -> PRs that delivered it, from the tracker's PR history."""
    found = defaultdict(list)
    known = backlog()
    text = TRACKER.read_text(encoding="utf-8")
    section = text.split("## PR history", 1)[1].split("\n## ", 1)[0]
    for line in section.splitlines():
        cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
        if len(cells) < 3 or not cells[0].startswith(("#", "(before", "(this item")):
            continue
        label = cells[0] if cells[0].startswith("#") else "before PRs"
        if cells[0].startswith("(this item"):
            label = "this PR"
        for ticket in _expand(cells[1], known):
            found[ticket].append(label)
    return found


@lru_cache(maxsize=1)
def record_tests() -> dict[str, set[str]]:
    """Ticket -> backend test files its record names as evidence."""
    found = defaultdict(set)
    for path in sorted(REQUIREMENTS.glob("*.md")):
        if path.name in {"README.md", TRACEABILITY.name}:
            continue
        ticket = None
        for line in path.read_text(encoding="utf-8").splitlines():
            match = re.fullmatch(r"### (HIMS-[A-Z]+-\d{3})", line.strip())
            if match:
                ticket = match.group(1)
            elif ticket and line.startswith("| Test evidence |"):
                found[ticket].update(re.findall(r"`((?:apps|common)/[\w/]+\.py)`", line))
    return found


@lru_cache(maxsize=1)
def requirement_records() -> dict[str, str]:
    """Ticket -> the requirement record file that describes it (``### HIMS-...`` headings)."""
    found = {}
    for path in sorted(REQUIREMENTS.glob("*.md")):
        if path.name in {"README.md", TRACEABILITY.name}:
            continue
        for line in path.read_text(encoding="utf-8").splitlines():
            match = re.fullmatch(r"### (HIMS-[A-Z]+-\d{3})", line.strip())
            if match:
                found[match.group(1)] = path.name
    return found


# --- Tests that call each endpoint -----------------------------------------------------------


def _test_files() -> list[Path]:
    return sorted(
        path
        for folder in ("apps", "common")
        for path in (BACKEND / folder).rglob("test_*.py")
        if "tests" in path.parts
    )


def _constants(tree) -> dict[str, str]:
    found = {}
    for node in tree.body:
        if (
            isinstance(node, ast.Assign)
            and len(node.targets) == 1
            and isinstance(node.targets[0], ast.Name)
            and isinstance(node.value, ast.Constant)
            and isinstance(node.value.value, str)
            and node.value.value.startswith("/api/")
        ):
            found[node.targets[0].id] = node.value.value
    return found


def _with_constants(text: str, constants: dict[str, str]) -> str:
    for name, value in constants.items():
        text = text.replace("{" + name + "}", value)
        text = re.sub(rf"(?<![\w\"'{{.]){name}(?![\w}}])", f'"{value}"', text)
    return text


@lru_cache(maxsize=1)
def test_functions() -> list[tuple[str, str]]:
    """(test id, source with URL constants written out) for every backend test."""
    found = []
    for path in _test_files():
        source = path.read_text(encoding="utf-8")
        tree = ast.parse(source)
        constants = _constants(tree)
        relative = path.relative_to(BACKEND).as_posix()
        for node in ast.walk(tree):
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name.startswith(
                "test_"
            ):
                text = _with_constants(ast.get_source_segment(source, node) or "", constants)
                found.append((f"{relative}::{node.name}", text))
    return found


def _path_pattern(path: str) -> re.Pattern:
    parts = []
    for piece in re.split(r"(\{[^}]+\})", path):
        if piece.startswith("{"):
            parts.append(r"(?:\{[^}]*\}|[^/\"'{}\s]+)")
        else:
            parts.append(re.escape(piece))
    body = "".join(parts)
    trimmed = body[:-1] if body.endswith("/") else body
    return re.compile(rf"(?<=[\"'}}]){trimmed}/?(?=[\"'?])")


def tests_for(endpoint) -> list[str]:
    pattern = _path_pattern(endpoint.path)
    call = f".{endpoint.method.lower()}("
    return [name for name, text in test_functions() if call in text and pattern.search(text)]


# --- Writing ---------------------------------------------------------------------------------


def _anchor(endpoint) -> str:
    return re.sub(r"[^a-z0-9]+", "-", f"{endpoint.method} {endpoint.path}".lower()).strip("-")


def _requirement_links(tickets, prefix: str) -> str:
    records = requirement_records()
    links = []
    for ticket in tickets:
        target = records.get(ticket)
        links.append(f"[{ticket}]({prefix}{target}#{ticket.lower()})" if target else ticket)
    return ", ".join(links) or "—"


def _actor(endpoint) -> str:
    if endpoint.access == inventory.PUBLIC:
        return "Anyone, without signing in (the answer reveals nothing about accounts or records)"
    if endpoint.access == inventory.SIGNED_IN:
        return "Anyone signed in, for their own account or the hospital-wide basics"
    roles = roles_by_permission().get(endpoint.permission, [])
    text = (
        f"`{endpoint.permission}` ({PERMISSIONS.get(endpoint.permission, '')}). "
        f"System roles holding it: {', '.join(roles) or 'none (custom roles only)'}. "
        "Privileged roles must have passed two-factor in this session"
    )
    if endpoint.confirm_identity:
        text += (
            '; a "confirm it\'s you" within the last '
            f"{setting_default('HIMS_CONFIRM_IDENTITY_MINUTES')} minutes is required"
        )
    return text


def _errors(endpoint, found: reach.Reach) -> str:
    statuses = {**_error_statuses(), **dict(found.statuses)}
    codes = set(found.error_codes)
    if endpoint.access != inventory.PUBLIC:
        codes.add("NOT_AUTHENTICATED")
    if endpoint.access == inventory.PERMISSION:
        codes.update({"PERMISSION_DENIED", "MFA_SETUP_REQUIRED"})
    if endpoint.confirm_identity:
        codes.add("REAUTH_REQUIRED")
    if "{" in endpoint.path:
        codes.add("NOT_FOUND")
    if endpoint.writes:
        codes.add("VALIDATION_ERROR")
    if endpoint.throttles:
        codes.add("RATE_LIMITED")
    codes.discard("DOMAIN_ERROR")
    ordered = sorted(codes, key=lambda code: (statuses.get(code, 999), code))
    return ", ".join(
        f"{statuses[code]} `{code}`" if code in statuses else f"`{code}`" for code in ordered
    )


def _concurrency(endpoint, request_fields: str, found: reach.Reach) -> str:
    if not endpoint.writes:
        return "None needed (read only)"
    text = []
    if "`version`" in request_fields:
        text.append(
            "Send the `version` you read; if the record changed since, 409 `STALE_RESOURCE` and "
            "nothing is saved"
        )
    if found.row_lock:
        text.append("the row is locked while it changes, so two requests never both win")
    if not text:
        return (
            "No version check (adds a new record or is a one-off action); unique rules in the "
            "database refuse duplicates"
        )
    joined = "; ".join(text)
    return joined[0].upper() + joined[1:]


def _transaction(endpoint, found: reach.Reach) -> str:
    if not endpoint.writes:
        if found.audit_actions:
            return "Read only; the audit event of the read is saved in its own transaction"
        return "Read only"
    if found.transaction:
        return (
            "One transaction: the change, its audit event and any background event are saved "
            "together or not at all"
        )
    return "Each statement on its own (no multi-row change); the audit event is saved with it"


def _timeouts(endpoint, found: reach.Reach) -> str:
    parts = []
    for label in found.external:
        if label.startswith("Messages"):
            parts.append(
                f"messages: email timeout {setting_default('EMAIL_TIMEOUT')} s; a failed message "
                "is retried every few minutes with a growing pause, up to "
                f"{setting_default('HIMS_NOTIFICATION_MAX_ATTEMPTS')} tries, then shows as failed "
                "with Send again"
            )
        elif label.startswith("Virus"):
            parts.append(
                f"virus scanner: {setting_default('HIMS_CLAMD_TIMEOUT')} s; if it cannot answer, "
                "the upload is refused (`SCANNER_UNAVAILABLE`), never let through unchecked"
            )
        elif label.startswith("PostgreSQL"):
            parts.append("PostgreSQL tools run with a time limit; a failure is `RECOVERY_FAILED`")
    if found.events:
        parts.append(
            "background events: the outbox dispatcher retries with back-off up to "
            f"{setting_default('HIMS_OUTBOX_MAX_ATTEMPTS')} times, then marks the event dead for "
            "the Background jobs page"
        )
    if not parts:
        parts.append("No outside calls inside the request")
    if endpoint.writes:
        parts.append(
            "the client may retry a lost answer with the same Idempotency-Key"
            if endpoint.idempotency
            else "the client should reload before retrying a lost answer"
        )
    return "; ".join(parts)


def _volume(endpoint) -> str:
    parts = [throttle_text(scope) for scope in endpoint.throttles]
    if endpoint.action == "list":
        parts.append("pages of 25 (`page_size` up to 100)")
    return "; ".join(parts) or "—"


def _tests(endpoint) -> str:
    names = tests_for(endpoint)
    if not names:
        return "Covered through the screen's browser tests and the requirement's tests (see record)"
    shown = ", ".join(f"`{name}`" for name in names[:_MAX_TESTS])
    more = len(names) - _MAX_TESTS
    return shown + (f" and {more} more" if more > 0 else "")


def _states(endpoint, found: reach.Reach) -> tuple[str, str]:
    if not endpoint.writes:
        return "Any", "Unchanged (read only)"
    refusals = [
        code
        for code in found.error_codes
        if any(
            word in code
            for word in ("STATE", "ALREADY", "INACTIVE", "NOT_", "CLOSED", "ENDED", "DECIDED")
        )
        and code not in _NOT_STATES
    ]
    allowed = (
        "Refused in the wrong state with " + ", ".join(f"`{code}`" for code in refusals)
        if refusals
        else "Any (no state rule)"
    )
    return allowed, "As in the purpose above; the new state is in the response and the audit event"


def _idempotency(endpoint) -> str:
    if not endpoint.writes:
        return "Not applicable (read only)"
    if not endpoint.idempotency:
        return "Not taken: repeating the request is refused by the state rules or is harmless"
    need = "required" if endpoint.idempotency == "required" else "optional"
    return (
        f"`Idempotency-Key` header ({need}; operation `{endpoint.idempotency_operation}`): "
        "the same key with the same body replays the stored answer (`Idempotent-Replayed: "
        "true`); with a different body 409 `IDEMPOTENCY_KEY_REUSED`; kept "
        f"{setting_default('HIMS_IDEMPOTENCY_RETENTION_HOURS')} hours"
    )


def endpoint_section(endpoint) -> str:
    found = reach.for_endpoint(endpoint)
    op = operation(endpoint)
    body = op.get("requestBody", {}).get("content")
    request_fields = _fields(body)
    responses = ", ".join(
        f"{code} {_schema_name(spec.get('content')) or spec.get('description', '')}".strip()
        for code, spec in sorted(op.get("responses", {}).items())
    )
    parameters = ", ".join(
        f"`{item['name']}`" for item in op.get("parameters", []) if item.get("in") == "query"
    )
    allowed, resulting = _states(endpoint, found)
    rows = [
        ("Endpoint ID", f"`{op.get('operationId', '—')}`"),
        ("Method and path", f"`{endpoint.method} {endpoint.path}`"),
        ("Business purpose", endpoint.summary or "—"),
        ("Requirements", _requirement_links(endpoint.requirements, "../../../requirements/")),
        ("Actor / permission required", _actor(endpoint)),
        ("Customer / facility scope", inventory.scope_label(endpoint)),
        (
            "Request schema",
            (_schema_name(body) + (f": {request_fields}" if request_fields else ""))
            or "No body" + (f"; query: {parameters}" if parameters else ""),
        ),
        ("Response schema", responses or "—"),
        (
            "Validation rules",
            "Fields as in the request schema; anything invalid is 400 `VALIDATION_ERROR` with "
            "each field's problem, and nothing is saved"
            if endpoint.writes
            else "Query values outside the allowed ones are refused (400) or ignored",
        ),
        ("Allowed current states", allowed),
        ("Resulting state", resulting),
        ("Idempotency key behavior", _idempotency(endpoint)),
        ("Concurrency control", _concurrency(endpoint, request_fields, found)),
        ("Database transaction", _transaction(endpoint, found)),
        (
            "Audit event",
            ", ".join(f"`{action}`" for action in found.audit_actions)
            or "None of its own (reads of configuration are not audited; a refusal records "
            "`access.denied`)",
        ),
        ("Outbox / domain event", ", ".join(f"`{event}`" for event in found.events) or "None"),
        ("External calls", "; ".join(found.external) or "None"),
        ("Timeout and retry policy", _timeouts(endpoint, found)),
        ("Expected error codes", _errors(endpoint, found)),
        ("Rate / volume assumptions", _volume(endpoint)),
        (
            "Metrics and alerts",
            "Request log line and trace span with `request_id`, status and time; response-time "
            "targets checked by the volume check (HIMS-OPS-017); hosted alarms with HIMS-OPS-004",
        ),
        ("Automated test cases", _tests(endpoint)),
        (
            "Backward-compatibility policy",
            "API v1 rules in [the API contracts guide](../README.md#versioning-and-breaking-"
            "changes); CI fails when `docs/api/openapi.yaml` differs from the code",
        ),
    ]
    table = "\n".join(f"| {label} | {value} |" for label, value in rows)
    return f"### {endpoint.method} {endpoint.path}\n\n| Field | Contract |\n|---|---|\n{table}\n"


def _area_endpoints():
    grouped = defaultdict(list)
    for endpoint in inventory.endpoints():
        grouped[endpoint.app_label].append(endpoint)
    unknown = set(grouped) - set(AREAS)
    if unknown:
        raise ValueError(f"Add these areas to common/contracts/generator.AREAS: {sorted(unknown)}")
    return [(label, grouped[label]) for label in AREAS if grouped.get(label)]


def area_file(label: str, endpoints) -> str:
    lines = [
        HEADER,
        f"# API contracts: {AREAS[label]}\n",
        "Each endpoint in the spec 29.5 template. Shared rules (errors, idempotency, versions, "
        "versioning): [API contracts guide](../README.md). Index: [all endpoints](README.md).\n",
    ]
    lines += [endpoint_section(endpoint) for endpoint in endpoints]
    return "\n".join(lines)


def index_file(areas) -> str:
    total = sum(len(items) for _, items in areas)
    lines = [
        HEADER,
        "# API endpoints (contracts index)\n",
        f"{total} endpoints under `/api/v1/`, read from the code. Each links to its full contract "
        "(spec 29.5) and its requirements (spec 25.3). Access: **public** (no sign-in), "
        "**signed in** (any account), or the permission named.\n",
    ]
    for label, endpoints in areas:
        lines.append(f"## [{AREAS[label]}]({label}.md)\n")
        lines.append("| Method and path | Access | Requirements |")
        lines.append("|---|---|---|")
        for endpoint in endpoints:
            access = (
                f"`{endpoint.permission}`"
                if inventory.PERMISSION == endpoint.access
                else endpoint.access.replace("_", " ")
            )
            link = f"[`{endpoint.method} {endpoint.path}`]({label}.md#{_anchor(endpoint)})"
            tickets = ", ".join(endpoint.requirements) or "—"
            lines.append(f"| {link} | {access} | {tickets} |")
        lines.append("")
    return "\n".join(lines)


def traceability_file() -> str:
    by_ticket = defaultdict(list)
    for endpoint in inventory.endpoints():
        for ticket in endpoint.requirements:
            by_ticket[ticket].append(endpoint)
    mentions = defaultdict(set)
    for name, text in test_functions():
        for ticket in set(_TICKET.findall(text)):
            mentions[ticket].add(name.split("::")[0])
    for path in _test_files():
        for ticket in set(_TICKET.findall(path.read_text(encoding="utf-8"))):
            mentions[ticket].add(path.relative_to(BACKEND).as_posix())
    endpoint_tests = defaultdict(set)
    for ticket, endpoints in by_ticket.items():
        for endpoint in endpoints:
            endpoint_tests[ticket].update(name.split("::")[0] for name in tests_for(endpoint))
    records = requirement_records()
    rows = []
    done = 0
    for ticket, (title, status) in backlog().items():
        short = status.split("(")[0].strip() or status
        if is_done(status):
            done += 1
        record = f"[record]({records[ticket]}#{ticket.lower()})" if ticket in records else "—"
        endpoints = by_ticket.get(ticket, [])
        api = f"{len(endpoints)}" if endpoints else "—"
        files = sorted(
            mentions.get(ticket, set())
            | endpoint_tests.get(ticket, set())
            | record_tests().get(ticket, set())
        )
        tests = f"{len(files)} files" if files else "—"
        prs = ", ".join(pull_requests().get(ticket, [])) or "—"
        clean = title.replace("|", "/")
        rows.append(f"| {ticket} | {clean} | {short} | {record} | {api} | {tests} | {prs} |")
    return "\n".join(
        [
            HEADER,
            "# Requirements traceability matrix (Phase 1)\n",
            "Every Phase 1 requirement (backlog ticket; ID scheme in "
            "[ADR-032](../decisions/ADR-032-requirement-ids-and-contract-docs.md)) traced to its "
            "requirement record, the API endpoints that deliver it "
            "([contracts](../architecture/api-and-integrations/endpoints/README.md)), the backend "
            "test files that name it or call its endpoints, and the pull requests that delivered "
            "it (spec 25.3). Browser tests and manual steps are named in each record.\n",
            f"{done} of {len(backlog())} marked Done in the backlog; {len(records)} requirement "
            "records (the approved compliance documents have records too). The tracker's count "
            "also includes the approvals of 2026-11-08.\n",
            "| ID | Requirement | Status | Record | API endpoints | Backend tests | PRs |",
            "|---|---|---|---|---|---|---|",
            *rows,
            "",
        ]
    )


def render() -> dict[Path, str]:
    areas = _area_endpoints()
    files = {ENDPOINT_DOCS / "README.md": index_file(areas)}
    for label, endpoints in areas:
        files[ENDPOINT_DOCS / f"{label}.md"] = area_file(label, endpoints)
    files[TRACEABILITY] = traceability_file()
    return files


def stale_files(files: dict[Path, str]) -> list[Path]:
    stale = [
        path
        for path, content in files.items()
        if not path.exists() or path.read_text(encoding="utf-8") != content
    ]
    extra = [
        path for path in ENDPOINT_DOCS.glob("*.md") if path not in files and ENDPOINT_DOCS.exists()
    ]
    return stale + extra


def write(files: dict[Path, str]) -> None:
    ENDPOINT_DOCS.mkdir(parents=True, exist_ok=True)
    REQUIREMENTS.mkdir(parents=True, exist_ok=True)
    for path in ENDPOINT_DOCS.glob("*.md"):
        if path not in files:
            path.unlink()
    for path, content in files.items():
        path.write_bytes(content.encode("utf-8"))
