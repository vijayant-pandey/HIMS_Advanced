"""Generate the data dictionary and ERDs from the live Django models (spec 28; HIMS-DATA-001).

Output (both generated, never edited by hand):

* ``docs/architecture/data-architecture/data-dictionary.md``: every table and column with type,
  nullability, default, allowed values, who sets it, sensitivity, keys, constraints, indexes,
  lifecycle and owning domain;
* ``docs/architecture/data-architecture/erd.md``: an overview ERD of all tables and one ERD per
  domain with columns (Mermaid, rendered by GitHub).

Regenerate with ``python manage.py data_dictionary``; ``--check`` fails when the committed files
are out of date (a test runs the same check in CI).
"""

from pathlib import Path

from django.apps import apps
from django.db import connection, models
from django.db.models import F, Q

from . import catalog

DOCS = Path(__file__).resolve().parents[3] / "docs" / "architecture" / "data-architecture"
DICTIONARY = DOCS / "data-dictionary.md"
ERD = DOCS / "erd.md"
HEADER = (
    "<!-- Generated by `python manage.py data_dictionary` from the Django models. "
    "Do not edit by hand: change the models or common/datadict/catalog.py and regenerate. -->\n"
)
# Timestamps a person (not the system) chooses.
PERSON_TIMES = {"valid_from", "valid_until", "starts_at", "ends_at", "due_on", "expires_at"}
# Columns that look person-chosen but are set by the system in these tables.
SYSTEM_COLUMNS = {
    "user_invitations.expires_at",
    "user_password_resets.expires_at",
    "idempotency_records.expires_at",
    "role_assignments.valid_from",
    "access_review_items.granted_at",
    "access_review_items.access_ends_at",
    "staff_credential_expiry_alerts.expires_at",
    "role_assignments.delegation_id",
    "role_assignments.delegated_from_id",
    "user_sessions.session_key",
    "user_mfa_devices.secret_encrypted",
    "user_mfa_recovery_codes.code_hash",
}
# Plain meanings for columns most tables share.
COMMON_MEANINGS = {
    "id": "Internal identity (random UUID; never shown as a business number)",
    "created_at": "When the row was created (UTC)",
    "updated_at": "When the row last changed (UTC)",
    "version": "Edit counter: a save based on an older version is refused (409)",
    "organization": "The hospital that owns the row (one per deployment)",
    "is_active": "Switched on (true) or off (false); rows are switched off, not deleted",
}
_LOOKUPS = {
    "exact": "=",
    "gt": ">",
    "gte": "≥",
    "lt": "<",
    "lte": "≤",
    "in": "in",
    "iexact": "= (any case)",
}


# --- Model discovery -------------------------------------------------------------------------


def domain_models() -> list[tuple[str, list[type[models.Model]]]]:
    result = []
    for label in catalog.DOMAINS:
        config = apps.get_app_config(label)
        result.append((label, [m for m in config.get_models() if not m._meta.proxy]))
    return result


def hims_tables() -> set[str]:
    return {m._meta.db_table for _, ms in domain_models() for m in ms}


# --- Formatting helpers -------------------------------------------------------------------------


def cell(value) -> str:
    text = " ".join(str(value).split())
    return text.replace("|", "\\|") or "—"


def format_q(q) -> str:
    """A readable condition, e.g. ``valid_until is empty OR valid_until > valid_from``."""
    if isinstance(q, Q):
        parts = [format_q(child) for child in q.children]
        joined = f" {q.connector} ".join(parts)
        if len(parts) > 1:
            joined = f"({joined})"
        return f"NOT {joined}" if q.negated else joined
    lookup, value = q
    field, _, operator = lookup.partition("__")
    operator = operator or "exact"
    if operator == "isnull":
        return f"{field} is {'empty' if value else 'set'}"
    shown = value.name if isinstance(value, F) else repr(value)
    return f"{field} {_LOOKUPS.get(operator, operator)} {shown}"


def db_type(field) -> str:
    if field.is_relation:
        target = field.target_field
        return (
            f"{target.db_type(connection)} → {field.related_model._meta.db_table}.{target.column}"
        )
    return field.db_type(connection) or field.get_internal_type()


def default_text(field) -> str:
    if getattr(field, "auto_now", False):
        return "now (on every save)"
    if getattr(field, "auto_now_add", False):
        return "now (on create)"
    if not field.has_default():
        return "—"
    default = field.default
    if callable(default):
        name = getattr(default, "__name__", type(default).__name__)
        return f"{name}()"
    if default == "":
        return "empty text"
    return f"`{default!r}`" if not isinstance(default, (list, dict)) else f"`{default}`"


def allowed_text(field) -> str:
    notes = []
    if field.choices:
        notes.append(", ".join(f"`{value}` ({label})" for value, label in field.flatchoices))
    elif isinstance(field, models.CharField) and field.max_length:
        notes.append(f"up to {field.max_length} characters")
    if isinstance(field, (models.PositiveIntegerField, models.PositiveBigIntegerField)):
        notes.append("0 or more")
    if field.unique and not field.primary_key:
        notes.append("unique")
    if field.is_relation:
        notes.append(f"on delete {field.remote_field.on_delete.__name__}")
    return "; ".join(notes)


def who_sets(table: str, field) -> str:
    name = field.name
    if f"{table}.{field.column}" in SYSTEM_COLUMNS:
        return "System"
    if field.primary_key or not field.editable or name in ("version", "created_at", "updated_at"):
        return "System"
    if name == "organization":
        return "System"
    if getattr(field, "auto_now", False) or getattr(field, "auto_now_add", False):
        return "System"
    if name.endswith("_by") or name in ("actor", "requested_by", "uploaded_by", "updated_by"):
        return "System (who did it)"
    if name.endswith("_at") and name not in PERSON_TIMES:
        return "System"
    return "Person"


def classify(table: str, field) -> tuple[str, str]:
    key = f"{table}.{field.column}"
    if key in catalog.COLUMN_OVERRIDES:
        return catalog.COLUMN_OVERRIDES[key]
    if field.name in catalog.NAME_RULES:
        return catalog.NAME_RULES[field.name]
    if table in catalog.RESTRICTED_TABLES:
        return catalog.RESTRICTED, "Security record"
    if field.is_relation:
        if field.related_model._meta.db_table == "users":
            return catalog.INTERNAL, "Person reference (id only)"
        return catalog.INTERNAL, "Reference"
    if field.primary_key or field.name in ("created_at", "updated_at", "version"):
        return catalog.INTERNAL, "System metadata"
    return catalog.INTERNAL, "Business data"


def purpose(model) -> str:
    doc = (model.__doc__ or "").strip()
    if not doc or doc.startswith(f"{model.__name__}("):  # Django's automatic docstring
        return ""
    return " ".join(doc.split("\n\n")[0].split())


def keys_and_rules(model) -> list[str]:
    meta = model._meta
    rules = []
    for constraint in meta.constraints:
        if isinstance(constraint, models.UniqueConstraint):
            fields = ", ".join(constraint.fields) or "(expression)"
            text = f"Unique: {fields}"
            if constraint.condition is not None:
                text += f" where {format_q(constraint.condition)}"
            if getattr(constraint, "nulls_distinct", None) is False:
                text += " (empty values count as equal)"
        elif isinstance(constraint, models.CheckConstraint):
            text = f"Check: {format_q(constraint.condition)}"
        else:
            text = type(constraint).__name__
        rules.append(f"`{constraint.name}`: {text}")
    for together in meta.unique_together:
        rules.append(f"Unique together: {', '.join(together)}")
    return rules


def index_list(model) -> list[str]:
    meta = model._meta
    found = []
    for index in meta.indexes:
        text = f"`{index.name}`: {', '.join(index.fields)}"
        if index.condition is not None:
            text += f" where {format_q(index.condition)}"
        found.append(text)
    for field in meta.concrete_fields:
        if field.db_index and not field.unique and not field.is_relation:
            found.append(f"{field.column} (single column)")
    return found


# --- Data dictionary ----------------------------------------------------------------------------


def render_dictionary() -> str:
    out = [
        HEADER,
        "# Data dictionary (Artifact A)\n",
        "Every table and column HIMS stores, generated from the code "
        "(spec 28.1 items 2, 3, 4 and 7). "
        "Read [README.md](README.md) first for the classification, lifecycle and access "
        "rules. Each hospital deployment has its own database with these tables (ADR-003).\n",
        "## Sensitivity levels\n",
        "| Level | Meaning |",
        "|---|---|",
        *[f"| **{level}** | {cell(text)} |" for level, text in catalog.LEVELS.items()],
        "",
        "**Set by:** *System* = HIMS fills it in; *Person* = entered on a screen, in the admin "
        "console or through the API (always checked by the services); *System (who did it)* "
        "= the signed-in person who made the change.\n",
        "Common to most tables: `id` is a random UUID (never a sequence), business numbers "
        "(employee number, MRN…) are separate columns, times are stored in UTC "
        "(`timestamp with time zone`), dates without time stay dates, foreign keys are "
        "indexed automatically, and `version` protects edits made at the same time "
        "(a stale save is refused with 409).\n",
        "## Contents\n",
    ]
    for label, model_list in domain_models():
        domain = catalog.DOMAINS[label]
        out.append(
            f"- **{domain['name']}**: "
            + ", ".join(f"[`{m._meta.db_table}`](#{m._meta.db_table})" for m in model_list)
        )
    out.append("")
    for label, model_list in domain_models():
        domain = catalog.DOMAINS[label]
        out.append(f"## {domain['name']}\n")
        out.append(f"**Owner (source of truth):** {domain['owner']}. ")
        if domain["docs"]:
            links = ", ".join(f"[{Path(d).stem}]({d})" for d in domain["docs"])
            out[-1] += f"**Design:** {links}."
        out.append("")
        for model in model_list:
            out.extend(render_table(model))
    return "\n".join(out).rstrip() + "\n"


def render_table(model) -> list[str]:
    meta = model._meta
    table = meta.db_table
    lines = [f'<a id="{table}"></a>', f"### `{table}`\n"]
    if purpose(model):
        lines.append(f"{purpose(model)}\n")
    lines.append(f"- **Model:** `{meta.app_label}.{model.__name__}`")
    lines.append(
        f"- **Lifecycle:** {catalog.LIFECYCLE.get(table, '**MISSING: add to catalog.py**')}"
    )
    rules = keys_and_rules(model)
    if rules:
        lines.append("- **Rules:** " + "; ".join(rules))
    indexes = index_list(model)
    if indexes:
        lines.append("- **Extra indexes:** " + "; ".join(indexes))
    lines += [
        "",
        "| Column | Type | Empty allowed | Default | Allowed values | Set by | Sensitivity "
        "| Meaning |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for field in meta.concrete_fields:
        level, category = classify(table, field)
        key = " **PK**" if field.primary_key else ""
        meaning = (
            field.help_text
            or COMMON_MEANINGS.get(field.name)
            or str(field.verbose_name).capitalize()
        )
        lines.append(
            "| "
            + " | ".join(
                [
                    f"`{field.column}`{key}",
                    cell(db_type(field)),
                    "yes" if field.null else "no",
                    cell(default_text(field)),
                    cell(allowed_text(field)),
                    who_sets(table, field),
                    f"{level}: {category}",
                    cell(meaning),
                ]
            )
            + " |"
        )
    lines.append("")
    return lines


# --- ERDs ---------------------------------------------------------------------------------


def _mermaid_type(field) -> str:
    raw = (field.target_field if field.is_relation else field).db_type(connection) or "unknown"
    raw = raw.split("(")[0].strip()
    return {
        "timestamp with time zone": "timestamptz",
        "character varying": "varchar",
        "double precision": "double",
    }.get(raw, raw.replace(" ", "_"))


def _relations(model_list, tables: set[str]) -> list[str]:
    lines = []
    for model in model_list:
        for field in model._meta.concrete_fields:
            if not field.is_relation:
                continue
            parent = field.related_model._meta.db_table
            if parent not in tables:
                continue
            parent_side = "|o" if field.null else "||"
            child_side = "o|" if field.one_to_one else "o{"
            child = model._meta.db_table
            lines.append(f'    {parent} {parent_side}--{child_side} {child} : "{field.column}"')
    return lines


def render_erd() -> str:
    all_models = [m for _, ms in domain_models() for m in ms]
    tables = hims_tables()
    out = [
        HEADER,
        "# Entity-relationship diagrams (Artifact A)\n",
        "Generated from the code (spec 28.1 items 1 and 2). "
        "Lines read: `||` exactly one, `|o` zero or "
        "one, `o{` zero or many, `o|` zero or one (one-to-one). The label is the foreign-key "
        "column. Column details are in [data-dictionary.md](data-dictionary.md).\n",
        "## All tables (physical overview)\n",
        "```mermaid",
        "erDiagram",
        *[f"    {m._meta.db_table}" for m in all_models],
        *_relations(all_models, tables),
        "```",
        "",
    ]
    for label, model_list in domain_models():
        domain = catalog.DOMAINS[label]
        own = {m._meta.db_table for m in model_list}
        out += [f"## {domain['name']} (logical)\n", "```mermaid", "erDiagram"]
        for model in model_list:
            out.append(f"    {model._meta.db_table} {{")
            for field in model._meta.concrete_fields:
                markers = []
                if field.primary_key:
                    markers.append("PK")
                if field.is_relation:
                    markers.append("FK")
                if field.unique and not field.primary_key:
                    markers.append("UK")
                suffix = f" {', '.join(markers)}" if markers else ""
                out.append(f"        {_mermaid_type(field)} {field.column}{suffix}")
            out.append("    }")
        relations = _relations(model_list, tables)
        outside = sorted(
            {line.split()[0] for line in relations} - own,
        )
        out += [f"    {table}" for table in outside]
        out += relations
        out += ["```", ""]
        if outside:
            out.append(
                "Tables from other domains are shown without columns: "
                + ", ".join(f"`{t}`" for t in outside)
                + ".\n"
            )
    return "\n".join(out).rstrip() + "\n"


def outputs() -> dict[Path, str]:
    return {DICTIONARY: render_dictionary(), ERD: render_erd()}
